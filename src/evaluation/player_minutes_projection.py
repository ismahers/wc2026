"""
Build WC2026 expected-minutes projections for player props.

The generated table is intentionally separate from manual overrides:
  - data/manual/player_expected_minutes_overrides_wc2026.csv is edited by humans
  - data/processed/player_expected_minutes_wc2026.csv is generated by this script

Usage:
  python -m src.evaluation.player_minutes_projection
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import numpy as np
import pandas as pd

from src.evaluation.player_prop_radar import data_quality, load_player_features


DEFAULT_FBREF_FEATURES = Path("data/processed/fbref_player_features_wc2026.csv")
DEFAULT_TM_FEATURES = Path("data/processed/player_prop_features_wc2026.csv")
DEFAULT_FIXTURES = Path("data/raw/group_stage_wc2026.csv")
DEFAULT_OVERRIDES = Path("data/manual/player_expected_minutes_overrides_wc2026.csv")
DEFAULT_OUTPUT = Path("data/processed/player_expected_minutes_wc2026.csv")
DEFAULT_SUMMARY = Path("outputs/wc2026_player_minutes_projection_summary.csv")
TARGET_TEAM_STARTERS = 11.0
TARGET_TEAM_MINUTES = 990.0

VALID_LINEUP_STATUSES = {
    "auto_projection",
    "locked_starter",
    "probable_starter",
    "rotation",
    "bench_option",
    "injury_doubt",
    "suspended",
    "out",
    "confirmed_starter",
    "confirmed_bench",
    "not_in_squad",
}

MANUAL_COLUMNS = [
    "match_number",
    "team",
    "opponent",
    "player_key",
    "player_name",
    "lineup_status",
    "manual_expected_minutes",
    "manual_start_probability",
    "minutes_source",
    "confidence",
    "notes",
]


def _num(value: object, default: float = 0.0) -> float:
    value = pd.to_numeric(value, errors="coerce")
    if pd.isna(value):
        return default
    return float(value)


def _clip(value: float, lower: float, upper: float) -> float:
    return float(min(max(value, lower), upper))


def _log_score(value: object, cap: float) -> float:
    value = _num(value)
    if value <= 0:
        return 0.0
    return _clip(math.log1p(value) / math.log1p(cap), 0.0, 1.0)


def position_broad(value: object) -> str:
    text = str(value or "").casefold()
    if "goalkeeper" in text or text == "gk":
        return "Goalkeeper"
    if "defender" in text or text in {"df", "cb", "lb", "rb"}:
        return "Defender"
    if "midfielder" in text or text in {"mf", "cm", "dm", "am"}:
        return "Midfielder"
    if "forward" in text or text in {"fw", "st", "winger"}:
        return "Forward"
    return "Unknown"


def starter_minutes(position: str) -> int:
    if position == "Goalkeeper":
        return 90
    if position == "Defender":
        return 82
    if position == "Midfielder":
        return 76
    if position == "Forward":
        return 72
    return 70


def bench_minutes(position: str) -> int:
    if position == "Goalkeeper":
        return 0
    if position == "Defender":
        return 12
    if position == "Midfielder":
        return 22
    if position == "Forward":
        return 25
    return 18


def role_score(row: pd.Series) -> float:
    fbref_minutes = _clip(_num(row.get("fbref_minutes")) / 3000.0, 0.0, 1.0)
    recent_minutes = _clip(_num(row.get("recent_minutes")) / 3000.0, 0.0, 1.0)
    market = _log_score(row.get("market_value_eur"), 100_000_000)
    caps = _clip(_num(row.get("international_caps")) / 80.0, 0.0, 1.0)
    return round(0.45 * fbref_minutes + 0.25 * recent_minutes + 0.20 * market + 0.10 * caps, 4)


def add_role_ranks(players: pd.DataFrame) -> pd.DataFrame:
    players = players.copy()
    players["position_broad_clean"] = players["position_broad"].map(position_broad)
    players["role_score"] = players.apply(role_score, axis=1)
    players["team_position_rank"] = (
        players.groupby(["team_canonical", "position_broad_clean"])["role_score"]
        .rank(method="first", ascending=False)
        .astype("Int64")
    )
    return players


def rank_base_start_probability(position: str, rank: int) -> float:
    if position == "Goalkeeper":
        if rank == 1:
            return 0.78
        if rank == 2:
            return 0.16
        return 0.04

    if position == "Defender":
        if rank <= 4:
            return 0.68
        if rank <= 7:
            return 0.34
        return 0.12

    if position == "Midfielder":
        if rank <= 4:
            return 0.66
        if rank <= 8:
            return 0.34
        return 0.14

    if position == "Forward":
        if rank <= 3:
            return 0.64
        if rank <= 7:
            return 0.34
        return 0.13

    return 0.20


def base_start_probability(row: pd.Series) -> tuple[float, str, float]:
    source = "fbref" if bool(row.get("has_fbref_season_stats", False)) else "transfermarkt_cards"
    tier, quality_score = data_quality(row, source=source)
    position = row["position_broad_clean"]
    rank = int(row["team_position_rank"]) if pd.notna(row.get("team_position_rank")) else 99

    p = rank_base_start_probability(position, rank)
    p += {
        "A": 0.08,
        "B": 0.04,
        "C": -0.04,
        "D": -0.10,
    }.get(tier, -0.10)

    p += 0.08 * row.get("role_score", 0.0)

    if _num(row.get("recent_minutes")) == 0 and _num(row.get("fbref_minutes")) == 0:
        p -= 0.08

    return round(_clip(p, 0.01, 0.95), 3), tier, quality_score


def lineup_status_from_probability(probability: float) -> str:
    if probability >= 0.75:
        return "locked_starter"
    if probability >= 0.52:
        return "probable_starter"
    if probability >= 0.20:
        return "rotation"
    return "bench_option"


def _expected_minutes_from_probability(position: str, probability: float) -> float:
    return probability * starter_minutes(position) + (1.0 - probability) * bench_minutes(position)


def confidence_from_player(row: pd.Series, tier: str, quality_score: float) -> float:
    base = 0.30 + 0.25 * row.get("role_score", 0.0) + 0.35 * quality_score
    if tier == "A":
        base += 0.08
    elif tier == "B":
        base += 0.04
    elif tier == "D":
        base -= 0.08
    return round(_clip(base, 0.20, 0.88), 3)


def normalize_base_projection(base: pd.DataFrame) -> pd.DataFrame:
    """Keep each team-match close to 11 expected starters and 990 player-minutes."""
    base = base.copy()

    for _, idx in base.groupby(["match_number", "team"]).groups.items():
        current_starters = base.loc[idx, "base_start_probability"].sum()
        if current_starters > 0:
            p = base.loc[idx, "base_start_probability"] * (TARGET_TEAM_STARTERS / current_starters)
            p = p.clip(lower=0.01, upper=0.98)
            rescaled_sum = p.sum()
            if rescaled_sum > 0:
                p = (p * (TARGET_TEAM_STARTERS / rescaled_sum)).clip(lower=0.01, upper=0.98)
            base.loc[idx, "base_start_probability"] = p.round(3)
            base.loc[idx, "final_start_probability"] = p.round(3)
            base.loc[idx, "lineup_status"] = p.map(lineup_status_from_probability)

        expected = base.loc[idx].apply(
            lambda row: _expected_minutes_from_probability(
                row["position_broad_clean"],
                row["base_start_probability"],
            ),
            axis=1,
        )
        total_minutes = expected.sum()
        if total_minutes > 0:
            expected = expected * (TARGET_TEAM_MINUTES / total_minutes)
        base.loc[idx, "base_expected_minutes"] = expected.round(1)
        base.loc[idx, "final_expected_minutes"] = expected.round(1)

    return base


def load_fixtures(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"No existe {path}")
    fixtures = pd.read_csv(path)
    required = {"match_number", "match_date", "home_team", "away_team"}
    missing = required.difference(fixtures.columns)
    if missing:
        raise ValueError(f"{path} no contiene columnas requeridas: {sorted(missing)}")
    return fixtures


def build_base_projection(players: pd.DataFrame, fixtures: pd.DataFrame) -> pd.DataFrame:
    players = add_role_ranks(players)
    rows: list[dict] = []

    for _, match in fixtures.iterrows():
        for team_col, opponent_col in [("home_team", "away_team"), ("away_team", "home_team")]:
            team = match[team_col]
            opponent = match[opponent_col]
            team_players = players[players["team_canonical"].eq(team)]

            for _, player in team_players.iterrows():
                position = player["position_broad_clean"]
                p_start, tier, quality_score = base_start_probability(player)
                s_min = starter_minutes(position)
                b_min = bench_minutes(position)
                expected_minutes = p_start * s_min + (1.0 - p_start) * b_min

                rows.append({
                    "match_number": match["match_number"],
                    "match_date": match["match_date"],
                    "stage": match.get("stage"),
                    "group": match.get("group"),
                    "team": team,
                    "opponent": opponent,
                    "player_key": player["player_key"],
                    "player_name": player["player_name"],
                    "position_broad": player["position_broad"],
                    "position_broad_clean": position,
                    "team_position_rank": player["team_position_rank"],
                    "role_score": player["role_score"],
                    "data_quality_tier": tier,
                    "data_quality_score": quality_score,
                    "base_start_probability": p_start,
                    "base_expected_minutes": round(expected_minutes, 1),
                    "manual_start_probability": np.nan,
                    "manual_expected_minutes": np.nan,
                    "final_start_probability": p_start,
                    "final_expected_minutes": round(expected_minutes, 1),
                    "lineup_status": lineup_status_from_probability(p_start),
                    "minutes_source": "auto_role_rank_heuristic",
                    "confidence": confidence_from_player(player, tier, quality_score),
                    "notes": "",
                })

    return normalize_base_projection(pd.DataFrame(rows))


def ensure_override_template(path: Path) -> None:
    if path.exists():
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(columns=MANUAL_COLUMNS).to_csv(path, index=False)


def read_overrides(path: Path) -> pd.DataFrame:
    ensure_override_template(path)
    overrides = pd.read_csv(path)
    missing = set(MANUAL_COLUMNS).difference(overrides.columns)
    if missing:
        raise ValueError(f"{path} no contiene columnas requeridas: {sorted(missing)}")

    overrides = overrides[MANUAL_COLUMNS].copy()
    overrides = overrides.dropna(how="all")
    if overrides.empty:
        return overrides

    invalid = sorted(set(overrides["lineup_status"].dropna()) - VALID_LINEUP_STATUSES)
    if invalid:
        raise ValueError(f"lineup_status no valido en {path}: {invalid}")

    overrides["match_number"] = pd.to_numeric(overrides["match_number"], errors="coerce").astype("Int64")
    overrides["manual_expected_minutes"] = pd.to_numeric(overrides["manual_expected_minutes"], errors="coerce")
    overrides["manual_start_probability"] = pd.to_numeric(overrides["manual_start_probability"], errors="coerce")
    overrides["confidence"] = pd.to_numeric(overrides["confidence"], errors="coerce")
    overrides = overrides.drop_duplicates(["match_number", "team", "player_key"], keep="last")
    return overrides


def _status_probability(status: object, base_probability: float) -> float:
    status = str(status or "")
    if status in {"out", "suspended", "not_in_squad"}:
        return 0.0
    if status == "confirmed_starter":
        return 1.0
    if status == "locked_starter":
        return max(base_probability, 0.88)
    if status == "probable_starter":
        return max(base_probability, 0.72)
    if status == "confirmed_bench":
        return 0.0
    if status == "bench_option":
        return min(base_probability, 0.18)
    if status == "rotation":
        return _clip(base_probability, 0.25, 0.50)
    if status == "injury_doubt":
        return min(base_probability, 0.25)
    return base_probability


def _minutes_from_probability(position: str, probability: float, status: object, base_minutes: float) -> float:
    status = str(status or "")
    if status in {"out", "suspended", "not_in_squad"}:
        return 0.0
    if status == "confirmed_bench":
        return float(bench_minutes(position))
    if status == "injury_doubt":
        return min(base_minutes, 30.0)
    return probability * starter_minutes(position) + (1.0 - probability) * bench_minutes(position)


def apply_manual_overrides(base: pd.DataFrame, overrides_path: Path) -> pd.DataFrame:
    base = base.copy()
    overrides = read_overrides(overrides_path)
    if overrides.empty:
        base["manual_override_applied"] = False
        return base

    merged = base.merge(
        overrides,
        on=["match_number", "team", "player_key"],
        how="left",
        suffixes=("", "_manual"),
    )
    has_override = merged["lineup_status_manual"].notna() | merged["manual_expected_minutes_manual"].notna()
    merged["manual_override_applied"] = has_override

    merged["manual_expected_minutes"] = merged["manual_expected_minutes_manual"].combine_first(
        merged["manual_expected_minutes"]
    )
    merged["manual_start_probability"] = merged["manual_start_probability_manual"].combine_first(
        merged["manual_start_probability"]
    )

    for col in ["lineup_status", "minutes_source", "confidence", "notes"]:
        manual_col = f"{col}_manual"
        if manual_col in merged.columns:
            merged[col] = merged[manual_col].combine_first(merged[col])

    merged["opponent"] = merged["opponent_manual"].combine_first(merged["opponent"])
    merged["player_name"] = merged["player_name_manual"].combine_first(merged["player_name"])

    status_probability = merged.apply(
        lambda row: _status_probability(row["lineup_status"], row["base_start_probability"]),
        axis=1,
    )
    merged["final_start_probability"] = merged["manual_start_probability"].combine_first(status_probability)
    merged["final_start_probability"] = merged["final_start_probability"].clip(lower=0, upper=1)

    status_minutes = merged.apply(
        lambda row: _minutes_from_probability(
            row["position_broad_clean"],
            row["final_start_probability"],
            row["lineup_status"],
            row["base_expected_minutes"],
        ),
        axis=1,
    )
    merged["final_expected_minutes"] = merged["manual_expected_minutes"].combine_first(status_minutes)
    merged["final_expected_minutes"] = merged["final_expected_minutes"].clip(lower=0, upper=90).round(1)

    if "minutes_source_manual" in merged.columns:
        merged["minutes_source"] = np.where(
            has_override & merged["minutes_source"].eq("auto_role_rank_heuristic"),
            "manual_status_override",
            merged["minutes_source"],
        )

    drop_cols = [col for col in merged.columns if col.endswith("_manual")]
    return normalize_final_minutes(merged.drop(columns=drop_cols))


def normalize_final_minutes(projections: pd.DataFrame) -> pd.DataFrame:
    projections = projections.copy()

    for _, idx in projections.groupby(["match_number", "team"]).groups.items():
        group = projections.loc[idx]
        manual_mask = group["manual_override_applied"].fillna(False).astype(bool)
        manual_sum = group.loc[manual_mask, "final_expected_minutes"].sum()

        if manual_sum >= TARGET_TEAM_MINUTES:
            total = group["final_expected_minutes"].sum()
            if total > 0:
                projections.loc[idx, "final_expected_minutes"] = (
                    group["final_expected_minutes"] * (TARGET_TEAM_MINUTES / total)
                ).round(1)
            continue

        auto_idx = group.index[~manual_mask]
        auto_sum = group.loc[~manual_mask, "final_expected_minutes"].sum()
        residual = TARGET_TEAM_MINUTES - manual_sum
        if len(auto_idx) and auto_sum > 0:
            projections.loc[auto_idx, "final_expected_minutes"] = (
                group.loc[~manual_mask, "final_expected_minutes"] * (residual / auto_sum)
            ).round(1)

    return projections


def build_summary(projections: pd.DataFrame) -> pd.DataFrame:
    return (
        projections.groupby(["minutes_source", "lineup_status"], as_index=False)
        .agg(
            rows=("player_key", "count"),
            players=("player_key", "nunique"),
            matches=("match_number", "nunique"),
            avg_expected_minutes=("final_expected_minutes", "mean"),
            avg_start_probability=("final_start_probability", "mean"),
            avg_confidence=("confidence", "mean"),
            manual_overrides=("manual_override_applied", "sum"),
        )
        .sort_values(["minutes_source", "lineup_status"])
        .round({
            "avg_expected_minutes": 1,
            "avg_start_probability": 3,
            "avg_confidence": 3,
        })
    )


def build_player_minutes_projection(
    fbref_features_path: Path = DEFAULT_FBREF_FEATURES,
    tm_features_path: Path = DEFAULT_TM_FEATURES,
    fixtures_path: Path = DEFAULT_FIXTURES,
    overrides_path: Path = DEFAULT_OVERRIDES,
    output_path: Path = DEFAULT_OUTPUT,
    summary_path: Path = DEFAULT_SUMMARY,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    players = load_player_features(fbref_features_path, tm_features_path)
    fixtures = load_fixtures(fixtures_path)
    base = build_base_projection(players, fixtures)
    projections = apply_manual_overrides(base, overrides_path)
    summary = build_summary(projections)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    summary_path.parent.mkdir(parents=True, exist_ok=True)
    projections.to_csv(output_path, index=False)
    summary.to_csv(summary_path, index=False)
    return projections, summary


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Build WC2026 expected-minutes projections for player props.")
    parser.add_argument("--fbref-features", default=str(DEFAULT_FBREF_FEATURES))
    parser.add_argument("--tm-features", default=str(DEFAULT_TM_FEATURES))
    parser.add_argument("--fixtures", default=str(DEFAULT_FIXTURES))
    parser.add_argument("--overrides", default=str(DEFAULT_OVERRIDES))
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT))
    parser.add_argument("--summary", default=str(DEFAULT_SUMMARY))
    return parser


def main() -> None:
    args = build_arg_parser().parse_args()
    projections, summary = build_player_minutes_projection(
        fbref_features_path=Path(args.fbref_features),
        tm_features_path=Path(args.tm_features),
        fixtures_path=Path(args.fixtures),
        overrides_path=Path(args.overrides),
        output_path=Path(args.output),
        summary_path=Path(args.summary),
    )

    print("\nPLAYER MINUTES PROJECTION")
    print("-" * 72)
    print(f"Rows: {len(projections):,}")
    print(f"Matches: {projections['match_number'].nunique()}")
    print(f"Players: {projections['player_key'].nunique()}")
    print(f"Manual overrides: {int(projections['manual_override_applied'].sum())}")
    print("\nSummary:")
    print(summary.to_string(index=False))
    print(f"\nSaved: {args.output}")
    print(f"Saved summary: {args.summary}")


if __name__ == "__main__":
    main()
